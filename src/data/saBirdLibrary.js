function slugify(value) {
  return String(value || '')
    .trim()
    .toLowerCase()
    .replace(/[â€™']/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
}

function makeBird(entry) {
  const funFacts = Array.isArray(entry.funFacts)
    ? entry.funFacts
    : [entry.funFact].filter(Boolean)

  return {
    id: entry.id || slugify(entry.commonName),
    commonName: entry.commonName,
    afrikaansName: entry.afrikaansName,
    scientificName: entry.scientificName,
    category: entry.category,
    tags: entry.tags || [entry.category],
    region: entry.region,
    habitat: entry.habitat,
    diet: entry.diet,
    colours: entry.colours,
    size: entry.size,
    whereFoundInSouthAfrica: entry.whereFoundInSouthAfrica || entry.region,
    description: entry.description,
    funFact: entry.funFact || funFacts[0] || '',
    funFacts,
    soundDescription: entry.soundDescription,
    imageUrl:
      entry.imageUrl ||
      birdPhotos[entry.commonName] ||
      `https://placehold.co/400x300?text=${encodeURIComponent(entry.commonName)}`,
    soundUrl: entry.soundUrl || '',
    rarity: entry.rarity || 'Common',
    special: Boolean(entry.special),
    featuredInMagazine: true,
    // Field-guide + nest + region details.
    mysteryClue: entry.mysteryClue || '',
    nest: entry.nest || null,
    regionTags: entry.regionTags || [],
    nearMe: Boolean(entry.nearMe),
    idTips: entry.idTips || '',
    similarSpecies: entry.similarSpecies || entry.similarBirds || [],
    bestTime: entry.bestTime || '',
    behaviour: entry.behaviour || '',
    callDescription: entry.callDescription || entry.soundDescription || '',
    conservationStatus: entry.conservationStatus || 'Least Concern',
    seen: false,
    firstSeenDate: '',
    lastSeenDate: '',
    timesSeen: 0,
    herPhotos: [],
    fieldNotes: '',
    spottedAt: '',
    myPhotos: [],
    aiDetails: null,
    birdCouncilReason: '',
  }
}

